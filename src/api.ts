export const fetchNews = (searchQuery?: string): Promise<INews[]> => {
  return new Promise<INews[]>((resolve) => {
    setTimeout(() => {
      if (!searchQuery || searchQuery.trim() === "") {
        resolve(MOCKED_NEWS);
        return;
      }

      const query = searchQuery.toLowerCase().trim();

      const filteredNews = MOCKED_NEWS.filter((news) => news.title.toLowerCase().includes(query) || news.description.toLowerCase().includes(query));

      resolve(filteredNews);
    }, 500);
  });
};
